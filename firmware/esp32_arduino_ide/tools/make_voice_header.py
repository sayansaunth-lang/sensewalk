"""Build voice_clips.h for the ESP32-S3 camera board from the clips in speech/audio/.

The board plays the same recorded clips as the laptop/Pi, through a MAX98357A I2S amplifier. To fit in
flash, each clip is resampled to 16 kHz mono and stored as 8-bit mu-law (G.711), half the size of 16-bit PCM
with good speech quality. The board decodes it on the fly.

    python firmware/esp32_arduino_ide/tools/make_voice_header.py          # rewrite the header
    python firmware/esp32_arduino_ide/tools/make_voice_header.py --check  # fail if the header is stale

Needs: pip install miniaudio numpy
"""
from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

import miniaudio
import numpy as np

ROOT = Path(__file__).resolve().parents[3]
AUDIO_DIR = ROOT / "speech" / "audio"
OUT = ROOT / "firmware" / "esp32_arduino_ide" / "SENSEWALK_cam_main" / "voice_clips.h"
SAMPLE_RATE = 16000

# (C identifier, wav file, what it says). Only the sounds the camera board can trigger: it detects
# people and potholes itself and hears brake events from the safety board. Vehicle/traffic clips stay on the Pi side.
CLIPS = [
    ("kClipPothole", "pothole_detected.wav", "Alert. Pothole detected ahead. Reduce speed."),
    ("kClipObstacle", "obstacle_warning.wav", "Warning, obstacle detected ahead. Slow down."),
    ("kClipRoadClear", "road_clear.wav", "Road ahead is clear."),
    ("kClipPerson", "person_ahead.wav", "Caution. Person ahead."),
]

BIAS = 0x84
CLIP_LEVEL = 32635


def lin2ulaw(sample: int) -> int:
    """G.711 mu-law encode of one 16-bit sample."""
    sign = 0x80 if sample < 0 else 0
    if sample < 0:
        sample = -sample
    sample = min(sample, CLIP_LEVEL) + BIAS
    exponent = 7
    mask = 0x4000
    while exponent > 0 and not (sample & mask):
        exponent -= 1
        mask >>= 1
    mantissa = (sample >> (exponent + 3)) & 0x0F
    return (~(sign | (exponent << 4) | mantissa)) & 0xFF


def ulaw2lin(byte: int) -> int:
    """G.711 mu-law decode of one byte (the same arithmetic the board uses)."""
    u = ~byte & 0xFF
    sample = (((u & 0x0F) << 3) + BIAS) << ((u & 0x70) >> 4)
    sample -= BIAS
    return -sample if (u & 0x80) else sample


def encode_wav(path: Path) -> bytes:
    decoded = miniaudio.decode_file(
        str(path), output_format=miniaudio.SampleFormat.SIGNED16, nchannels=1, sample_rate=SAMPLE_RATE
    )
    pcm = np.frombuffer(decoded.samples, dtype=np.int16)
    return bytes(lin2ulaw(int(s)) for s in pcm)


def build() -> str:
    lines = [
        "// GENERATED by firmware/esp32_arduino_ide/tools/make_voice_header.py from speech/audio/*.wav - do not edit.",
        f"// {SAMPLE_RATE} Hz, mono, 8-bit mu-law (G.711). Decode with voice.h.",
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace sensewalk::voice {",
        "",
        f"constexpr int kSampleRate = {SAMPLE_RATE};",
        f"constexpr int kClipCount = {len(CLIPS)};",
        "",
    ]
    names = []
    for i, (ident, wav, says) in enumerate(CLIPS):
        data = encode_wav(AUDIO_DIR / wav)
        lines.append(f"// {wav}: \"{says}\" ({len(data) / SAMPLE_RATE:.2f} s)")
        lines.append(f"constexpr int {ident} = {i};")
        lines.append(f"static const uint8_t kClipData{i}[{len(data)}] = {{")
        for j in range(0, len(data), 24):
            lines.append("    " + ",".join(f"0x{b:02X}" for b in data[j:j + 24]) + ",")
        lines.append("};")
        lines.append("")
        names.append((i, len(data), wav))
    lines.append("static const uint8_t* const kClipPtr[kClipCount] = {" + ", ".join(f"kClipData{i}" for i, _, _ in names) + "};")
    lines.append("static const int kClipLen[kClipCount] = {" + ", ".join(str(n) for _, n, _ in names) + "};")
    lines.append("static const char* const kClipName[kClipCount] = {" + ", ".join(f'"{w}"' for _, _, w in names) + "};")
    lines.append("")
    lines.append("}  // namespace sensewalk::voice")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="exit 1 if voice_clips.h does not match the WAV files")
    args = ap.parse_args()
    text = build()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if hashlib.sha256(current.replace("\r\n", "\n").encode()).digest() != hashlib.sha256(text.encode()).digest():
            print("voice_clips.h is stale: run make_voice_header.py")
            return 1
        print("voice_clips.h is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(text) // 1024} KB source, {len(CLIPS)} clips)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
