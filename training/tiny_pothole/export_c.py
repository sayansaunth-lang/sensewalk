"""Export the trained tiny pothole classifier as C++ headers for the ESP32-S3 camera board.

Folds BatchNorm into the convolutions and writes float32 weights, plus a handful of held-out test
views with PyTorch's exact outputs ("golden" vectors) so the C++ inference code can be proved to
match PyTorch (see firmware/esp32_arduino_ide/tools/test_pothole_net.cpp, run by CI, and the
self-test that runs at boot on the board).

    python training/tiny_pothole/export_c.py --weights tiny_pothole_w16.pt --views test_views.npy \
        --width 16 --threshold 0.73 --out firmware/esp32_arduino_ide/SENSEWALK_cam_main
"""
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import torch

from train_tiny_pothole import Net, prep


def fold(conv_w: torch.Tensor, bn) -> tuple[np.ndarray, np.ndarray]:
    scale = bn.weight / torch.sqrt(bn.running_var + bn.eps)
    w = conv_w * scale.view(-1, 1, 1, 1)
    b = bn.bias - bn.running_mean * scale
    # PyTorch [out][in][ky][kx] -> C layout [out][ky][kx][in]
    return w.detach().permute(0, 2, 3, 1).contiguous().numpy(), b.detach().numpy()


def arr(name: str, a: np.ndarray, per_line: int = 8) -> str:
    flat = a.reshape(-1)
    lines = []
    for i in range(0, len(flat), per_line):
        lines.append("    " + ", ".join(f"{v:.9g}f" for v in flat[i:i + per_line]) + ",")
    return f"static const float {name}[{len(flat)}] = {{\n" + "\n".join(lines) + "\n};\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--weights", required=True, type=Path)
    ap.add_argument("--views", required=True, type=Path)
    ap.add_argument("--width", type=int, default=16)
    ap.add_argument("--threshold", type=float, required=True)
    ap.add_argument("--out", required=True, type=Path)
    args = ap.parse_args()

    model = Net(args.width)
    model.load_state_dict(torch.load(args.weights))
    model.eval()
    convs = [m for m in model.features if isinstance(m, torch.nn.Conv2d)]
    bns = [m for m in model.features if isinstance(m, torch.nn.BatchNorm2d)]
    chans = [1] + [c.out_channels for c in convs]

    out = ["// GENERATED by training/tiny_pothole/export_c.py - do not edit by hand.",
           "// Tiny pothole classifier: 4 stride-2 3x3 convolutions (BatchNorm folded in) + global average pool + 2-way dense.",
           "// Input: 64x64 grayscale, normalised as (pixel - 128) / 128. Output: 2 logits [no pothole, pothole].",
           "#pragma once", "", "namespace sensewalk::pothole {", "",
           f"constexpr int kC1 = {chans[1]};", f"constexpr int kC2 = {chans[2]};",
           f"constexpr int kC3 = {chans[3]};", f"constexpr int kC4 = {chans[4]};",
           f"constexpr float kThreshold = {args.threshold}f;  // chosen on validation views for roughly 5% false alarms", ""]
    for i, (conv, bn) in enumerate(zip(convs, bns), start=1):
        w, b = fold(conv.weight.detach(), bn)
        out.append(arr(f"kW{i}", w))
        out.append(arr(f"kB{i}", b))
    out.append(arr("kFcW", model.fc.weight.detach().numpy()))
    out.append(arr("kFcB", model.fc.bias.detach().numpy()))
    out.append("}  // namespace sensewalk::pothole\n")
    (args.out / "pothole_weights.h").write_text("\n".join(out), encoding="utf-8")

    views = np.load(args.views)[:12]
    with torch.no_grad():
        logits = model(prep(views)).numpy()
    g = ["// GENERATED by training/tiny_pothole/export_c.py: held-out test views and PyTorch's exact logits.",
         "#pragma once", "#include <cstdint>", "", "namespace sensewalk::pothole {", "",
         f"constexpr int kGoldenCount = {len(views)};",
         "static const uint8_t kGoldenViews[kGoldenCount][64 * 64] = {"]
    for v in views:
        g.append("    {" + ",".join(str(int(x)) for x in v.reshape(-1)) + "},")
    g.append("};")
    g.append(arr("kGoldenLogits", logits, per_line=2))
    g.append("}  // namespace sensewalk::pothole\n")
    (args.out / "pothole_golden.h").write_text("\n".join(g), encoding="utf-8")
    n_params = sum(p.numel() for p in model.parameters())
    print(f"wrote pothole_weights.h and pothole_golden.h ({n_params} parameters, {len(views)} golden views)")


if __name__ == "__main__":
    main()
